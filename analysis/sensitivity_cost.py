"""Sensitivity of the strategy selection to the cost weights of Eq. (cost), to SC, and to admitting B4.

    python sensitivity_cost.py RESULTS_ROOT [--out ../generated]

The missed area in hectares is recovered from the stored criterion:
    M_ha = (C - c_t*T - c_p*applied) / c_m   with the benchmark weights (2.5, 40, 300).
For every weight set, the selected strategy is the feasible obstacle strategy (B1-B3; with --b4 also B4)
with minimum C. Instances with no feasible strategy are reported as "none".
Writes tab_sens.tex and numbers_sens.tex.
"""
import argparse
import os

import numpy as np
import pandas as pd

BASE = dict(c_t=2.5, c_p=40.0, c_m=300.0)
W = {12: "Twelve", 24: "TwentyFour", 36: "ThirtySix"}


def prep(df):
    df = df.copy()
    df["error"] = df["error"].fillna("").astype(str).replace("nan", "")
    df["feasible"] = df.feasible.astype(str).str.lower().isin(["true", "1"]) & df.error.eq("")
    df["missed_ha"] = (df.crit_C - BASE["c_t"] * df.time_min - BASE["c_p"] * df.applied_ha) / BASE["c_m"]
    return df


def select(df, c_t, c_p, c_m, strategies):
    d = df[df.strategy.isin(strategies) & df.feasible].copy()
    d["C"] = c_t * d.time_min + c_p * d.applied_ha + c_m * d.missed_ha
    best = d.loc[d.groupby("instance_id").C.idxmin(), ["instance_id", "strategy"]].set_index("instance_id").strategy
    inst = df[["instance_id", "width_m"]].drop_duplicates().set_index("instance_id")
    return inst.assign(sel=best).fillna({"sel": "none"})


def shares(sel):
    return (sel.groupby("width_m").sel.value_counts(normalize=True).unstack(fill_value=0) * 100)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "generated"))
    a = ap.parse_args()
    r = prep(pd.read_csv(os.path.join(a.root, "benchmark_v1_2", "runs.csv")))
    r = r[r.gate_type.astype(str).str.contains("road") & (r.density_per_ha > 0)]
    S3 = ["B1", "B2", "B3"]
    on, off = r[r.sc == 1], r[r.sc == 0]
    base = select(on, **BASE, strategies=S3)

    grid = []
    for c_t in (1.25, 2.5, 5.0):
        for c_p in (20.0, 40.0, 80.0):
            for c_m in (0.0, 100.0, 300.0, 1000.0, 3000.0):
                s = select(on, c_t, c_p, c_m, S3)
                agree = (s.sel == base.sel).mean() * 100
                sh = shares(s)
                grid.append(dict(c_t=c_t, c_p=c_p, c_m=c_m, agree=agree,
                                 **{f"B3_w{w}": sh.loc[w].get("B3", 0.0) for w in (12, 24, 36)}))
    g = pd.DataFrame(grid)
    sel_off = select(off, **BASE, strategies=S3)

    # B4 admitted (E3 cases): B1/B2 from E1, B3/B4 from E3 (same instances)
    b = prep(pd.read_csv(os.path.join(a.root, "b4_v1", "runs.csv")))
    b = b[b.sc == 1]
    e3 = pd.concat([on[on.instance_id.isin(b.instance_id) & on.strategy.isin(["B1", "B2"])],
                    b[b.strategy.isin(["B3", "B4"])]], ignore_index=True)
    sel_e3 = select(e3, **BASE, strategies=["B1", "B2", "B3"])
    sel_e3b4 = select(e3, **BASE, strategies=["B1", "B2", "B3", "B4"])

    # table: selection shares by width under baseline, SC off, extreme weights, and with B4
    rows = [("Baseline weights, SC on", shares(base)),
            ("SC off", shares(sel_off)),
            ("$c_m=0$ (missed area free)", shares(select(on, 2.5, 40, 0, S3))),
            ("$c_m=3000$", shares(select(on, 2.5, 40, 3000, S3))),
            ("E3 cases, B1--B3", shares(sel_e3)),
            ("E3 cases, B1--B4", shares(sel_e3b4))]
    cols = ["B1", "B2", "B3", "B4", "none"]
    L = [r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
         r"Scenario & $w$ & B1 & B2 & B3 & B4 & none \\", r"\midrule"]
    for name, sh in rows:
        for i, w in enumerate((12, 24, 36)):
            vals = [sh.loc[w].get(c, 0.0) if w in sh.index else 0.0 for c in cols]
            if "B4" not in name:
                vals[3] = np.nan
            cells = " & ".join("--" if pd.isna(v) else f"{v:.0f}" for v in vals)
            L.append(f"{name if i == 0 else ''} & {w} & {cells} \\\\")
        L.append(r"\addlinespace")
    L[-1] = r"\botrule"
    L.append(r"\end{tabular}")
    with open(os.path.join(a.out, "tab_sens.tex"), "w") as fh:
        fh.write("% generated by analysis/sensitivity_cost.py; do not edit\n" + "\n".join(L) + "\n")

    nums = {
        "SensNGrid": (len(g), 0),
        "SensAgreeMin": (g.agree.min(), 0),
        "SensAgreeMed": (g.agree.median(), 0),
        "SensAgreeCmPos": (g[g.c_m > 0].agree.min(), 0),
        "SensOffAgree": ((sel_off.sel == base.sel).mean() * 100, 0),
        "SensBFourSelPct": (shares(sel_e3b4).stack().loc[(slice(None), "B4")].mean(), 0),
    }
    gp = g[g.c_m > 0]
    for w in (12, 24, 36):
        nums[f"SensBThreeMinPosW{W[w]}"] = (gp[f"B3_w{w}"].min(), 0)
        nums[f"SensBThreeMaxPosW{W[w]}"] = (gp[f"B3_w{w}"].max(), 0)
        nums[f"SensBOneSelOffW{W[w]}"] = (shares(sel_off).loc[w].get("B1", 0.0), 0)
        nums[f"SensBOneSelOnW{W[w]}"] = (shares(base).loc[w].get("B1", 0.0), 0)
        nums[f"SensBOneSelBFourW{W[w]}"] = (shares(sel_e3b4).loc[w].get("B1", 0.0), 0)
    for w in (12, 24, 36):
        nums[f"SensBThreeMinW{W[w]}"] = (g[f"B3_w{w}"].min(), 0)
        nums[f"SensBThreeMaxW{W[w]}"] = (g[f"B3_w{w}"].max(), 0)
        nums[f"SensBFourSelW{W[w]}"] = (shares(sel_e3b4).loc[w].get("B4", 0.0), 0)
        nums[f"SensBThreeOffW{W[w]}"] = (shares(sel_off).loc[w].get("B3", 0.0), 0)
        nums[f"SensBThreeOnW{W[w]}"] = (shares(base).loc[w].get("B3", 0.0), 0)
    with open(os.path.join(a.out, "numbers_sens.tex"), "w") as fh:
        fh.write("% generated by analysis/sensitivity_cost.py; do not edit\n")
        for k, (v, p) in nums.items():
            t = f"{v:.{p}f}"
            t = r"\ensuremath{-}" + t[1:] if t.startswith("-") else t
            fh.write(f"\\newcommand{{\\num{k}}}{{{t}}}\n")
    print(g.round(1).to_string())
    for name, sh in rows:
        print(name); print(sh.round(1))
    print(nums)


if __name__ == "__main__":
    main()
