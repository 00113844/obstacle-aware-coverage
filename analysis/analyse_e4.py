def numbers(d, s, t, out):
    nums = {}
    nums["EFInstances"] = d.instance_id.nunique()
    nums["EFRows"] = len(d)
    nums["EFErrors"] = int((d.error != "").sum())
    nums["EFPlans"] = int(len(s))
    for r in RATIOS:
        R = RWORD[r]
        for st in ["A", "B1", "B2", "B3", "B3c", "B3n", "B3n_k2", "B3n_s12", "B4", "B3c_ctr", "B3n_ctr"]:
            if (r, st) not in t.index:
                continue
            x = t.loc[(r, st)]
            S = SWORD[st]
            nums[f"EF{S}{R}Feas"] = 100 * x.feas
            nums[f"EF{S}{R}Valid"] = 100 * x.valid
            nums[f"EF{S}{R}ValidSeed"] = 100 * x.valid_seed
            nums[f"EF{S}{R}NoCross"] = 100 * x.nocross
            nums[f"EF{S}{R}Cross"] = int(np.ceil(x.cross))      # medians of counts, printed as integers
            nums[f"EF{S}{R}Clear"] = 100 * x.clear
            nums[f"EF{S}{R}Ok"] = 100 * x.ok
            nums[f"EF{S}{R}LanesOk"] = 100 * x.lanes_ok
            nums[f"EF{S}{R}Breaks"] = int(np.ceil(x.brk))
            nums[f"EF{S}{R}OffLaneKm"] = x.offl / 1000
            nums[f"EF{S}{R}Unsown"] = x.sown
            nums[f"EF{S}{R}Traf"] = x.traf
    # drive-around: share of feasible B3 plans with at least one crossing, all ratios
    b3 = s[(s.strategy == "B3") & s.feasible]
    nums["EFBThreeAnyCrossPct"] = 100 * (b3.n_lane_crossings > 0).mean()
    # best drive-around variant per ratio (CTF-valid share over all paddocks); B4 (straddle) separate
    DA = ["B3", "B3c", "B3n", "B3n_k2", "B3n_s12"]
    da = s[s.strategy.isin(DA)]
    best = t.loc[[(r, x) for r in RATIOS for x in DA if (r, x) in t.index], "ok"].groupby(level=0).max()
    for r in RATIOS:
        nums[f"EFBestDA{RWORD[r]}Ok"] = 100 * best[r]
    nums["EFBestDAWideOk"] = 100 * max(best["2:1"], best["3:1"])
    # any drive-around CTF-valid plan count, 2:1 and 3:1
    nums["EFDAOkWideN"] = int(da[da.module_ratio.isin(["2:1", "3:1"])].ctf_ok.sum())
    nums["EFDAWideN"] = int(len(da[da.module_ratio.isin(["2:1", "3:1"])]))
    # paddocks without any CTF-valid layout (all strategies)
    anyok = s.groupby(["module_ratio", "instance_id"]).ctf_ok.any()
    for r in RATIOS:
        nums[f"EFNoneOk{RWORD[r]}Pct"] = 100 * (1 - anyok[r].mean())
        b1 = s[(s.module_ratio == r) & (s.strategy == "B1") & s.feasible]
        nums[f"EFBOne{RWORD[r]}FeasInvalidPct"] = 100 * (1 - b1.lanes_ok.mean())
    # off-lane ratio B1 / B3
    for r in RATIOS:
        nums[f"EFOffLaneRatio{RWORD[r]}Pct"] = 100 * (t.loc[(r, "B1")].offl / t.loc[(r, "B3")].offl - 1)
    # Part 3: constrained seeder and harvester routes
    p = d[(d.part3 == 1) & (d.lane_layout == "shared")].copy()
    p["season"] = p.time_min + p.seeder_time_min + p.harvester_time_min
    nums["EFPartThreeN"] = p.instance_id.nunique()
    nums["EFPartThreePerSys"] = p[p.strategy == "B1"].groupby("module_ratio").instance_id.nunique().min()
    for r in RATIOS:
        R = RWORD[r]
        for st in ["B1", "B3"]:
            x = p[(p.module_ratio == r) & (p.strategy == st)]
            S = SWORD[st]
            nums[f"EFP{S}{R}Spray"] = x.time_min.mean()
            nums[f"EFP{S}{R}Seed"] = x.seeder_time_min.mean()
            nums[f"EFP{S}{R}Harv"] = x.harvester_time_min.mean()
            nums[f"EFP{S}{R}Season"] = x.season.mean()
            nums[f"EFP{S}{R}TrafSeason"] = x.unique_trafficked_season_ha.mean()
            nums[f"EFP{S}{R}FeasN"] = int(x.feasible.sum())
        nums[f"EFPSeasonDiff{R}Pct"] = 100 * (nums[f"EFPBOne{R}Season"] / nums[f"EFPBThree{R}Season"] - 1)
        w = p[p.module_ratio == r].pivot_table(index="instance_id", columns="strategy",
                                               values=["season", "feasible"], aggfunc="first")
        nums[f"EFPBOneSlower{R}N"] = int((w["season"]["B1"] > w["season"]["B3"]).sum())
        nums[f"EFPPairs{R}N"] = int(len(w))
        both = w[(w["feasible"]["B1"].astype(bool)) & (w["feasible"]["B3"].astype(bool))]
        nums[f"EFPBothFeas{R}N"] = int(len(both))
        nums[f"EFPPairedDiff{R}Pct"] = (100 * (both["season"]["B1"] / both["season"]["B3"] - 1).median()
                                        if len(both) else float("nan"))
    with open(os.path.join(out, "numbers_e4.tex"), "w") as fh:
        fh.write("% generated by analysis/analyse_e4.py; do not edit\n")
        for k, v in nums.items():
            if isinstance(v, (int, np.integer)):
                txt = f"{int(v)}"
            elif abs(v - round(v)) < 1e-9 and abs(v) >= 10:
                txt = f"{v:.0f}"
            elif abs(v) >= 10:
                txt = f"{v:.0f}"
            else:
                txt = f"{v:.1f}"
            txt = r"\ensuremath{-}" + txt[1:] if txt.startswith("-") else txt
            fh.write(f"\\newcommand{{\\num{k}}}{{{txt}}}\n")
    return nums


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--out", default="paper/generated")
    ap.add_argument("--stem", default="rectangle_mixed_poisson_d1_w24_road_s0")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    d = load(a.root)
    s = main_set(d)
    t = summary(s)
    with pd.option_context("display.width", 250, "display.max_columns", 30, "display.max_rows", 200):
        print(t.round(3))
    tab_ctf(t, a.out)
    nums = numbers(d, s, t, a.out)
    for k in sorted(nums):
        if k.startswith(("EFBestDA", "EFOffLaneRatio", "EFPSeason", "EFBThreeAny", "EFDA")):
            print(k, round(float(nums[k]), 2))
    if os.path.exists(os.path.join(a.root, "geojson", a.stem + ".geojson")):
        rows = {r.strategy: r for r in d[(d.instance_id == a.stem) & (d.lane_layout == "shared")].itertuples()}
        n = int(d[d.instance_id == a.stem].n_ratio.iloc[0])
        fig_lanes(a.root, a.stem, n, rows, a.out)


if __name__ == "__main__":
    main()
