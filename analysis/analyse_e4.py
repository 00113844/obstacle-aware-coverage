def _tools():
    import sys
    here = os.path.dirname(os.path.abspath(__file__))
    for rel in (("..", "tools"), ("..", "..", "tools")):      # release layout, then paper-repo layout
        p = os.path.normpath(os.path.join(here, *rel))
        if os.path.isdir(p):
            sys.path.insert(0, p)
            break
    import ctf_geom  # noqa: E402  (the benchmark's own lane construction)
    return ctf_geom


def lanes_for(swaths, n, w_b=12.0, r_check=8.0):
    """Base lanes exactly as scored in E4 (ctf_geom.make_lanes, shared layout)."""
    cg = _tools()
    return [ln["line"] for ln in cg.make_lanes(swaths, n * w_b, w_b, "shared", r_check)]


def crossings(lanes):
    """Crossing points of pairs of lanes that cross (same predicate as ctf_geom.crossings)."""
    import shapely
    pts = []
    if len(lanes) < 2:
        return pts
    tree = shapely.STRtree(lanes)
    ia, ib = tree.query(lanes, predicate="crosses")
    for i, j in zip(ia, ib):
        if i >= j:
            continue
        x = lanes[i].intersection(lanes[j])
        for gm in getattr(x, "geoms", [x]):
            if gm.geom_type == "Point":
                pts.append((gm.x, gm.y))
            elif not gm.is_empty:
                c = gm.representative_point()
                pts.append((c.x, c.y))
    return pts


def fig_lanes(root, stem, n, rows, out):
    with open(os.path.join(root, "geojson", stem + ".geojson")) as fh:
        g = json.load(fh)
    F = g["features"]
    pad = shape([f for f in F if f["properties"].get("layer") == "paddock"][0]["geometry"])
    obs = [(f["properties"].get("kind"), shape(f["geometry"])) for f in F if f["properties"].get("layer") == "obstacle"]
    panels = ["B1", "B3", "B3c", "B3n"]
    title = {"B1": "B1 holes", "B3": "B3 drive-around", "B3c": "B3c CTF fillets", "B3n": "B3n nested detours"}
    fig, axs = plt.subplots(1, 4, figsize=(W2, 52 * MM))
    xmin, ymin, xmax, ymax = pad.bounds
    for k, (ax, s) in enumerate(zip(axs, panels)):
        sw = [shape(f["geometry"]) for f in F if f["properties"].get("kind") == "swath"
              and f["properties"].get("strategy") == s]
        hl = [shape(f["geometry"]) for f in F if f["properties"].get("kind") == "headland_pass"
              and f["properties"].get("strategy") == s]
        lanes = lanes_for(sw, n)
        import shapely
        bad = set()
        if len(lanes) > 1:
            ia, ib = shapely.STRtree(lanes).query(lanes, predicate="crosses")
            bad = {int(i) for i, j in zip(ia, ib) if i != j}
        ax.fill(*pad.exterior.xy, color="#f4f2ec", lw=0)
        ax.plot(*pad.exterior.xy, color=MUTED, lw=0.6)
        for h in hl:
            ax.plot(*h.xy, color="#c9c6bd", lw=0.5)
        for i, ln in enumerate(lanes):
            if i not in bad:
                ax.plot(*ln.xy, color="#2a5d8f", lw=0.55)
        for i in sorted(bad):
            ax.plot(*lanes[i].xy, color="#d03b3b", lw=0.75, zorder=4)
        for kind, o in obs:
            for gm in getattr(o, "geoms", [o]):
                ax.fill(*gm.exterior.xy, color="#2f7d3b" if kind == "tree" else "#8c6d4f", lw=0, zorder=5)
        pts = bad
        r = rows.get(s)
        sub = title[s]
        if r is not None:
            sub += "\n" + ("sprayer feasible" if r.feasible else "sprayer infeasible") + \
                f",\n{int(r.n_lane_crossings)} crossing lane pairs"
        ax.set_title(sub, color=INK, fontsize=7)
        ax.set_xlim(xmin - 5, xmax + 5)
        ax.set_ylim(ymin - 5, ymax + 5)
        ax.set_aspect("equal")
        ax.axis("off")
        panel_label(ax, "abcd"[k])
        print(f"  {s}: {len(lanes)} lanes, {len(pts)} lanes in crossings (runs.csv: {int(r.n_lane_crossings) if r is not None else '?'})")
    fig.savefig(os.path.join(out, "fig_ctf_lanes.pdf"))
    plt.close(fig)


