"""E4 (request R10): controlled-traffic tramline analysis.

    uv run --no-project --with numpy --with pandas --with matplotlib --with shapely \
        python paper/analysis/analyse_e4.py results/ctf_v1 --out paper/generated

Reads results/ctf_v1/runs.csv (one row per instance x strategy x lane layout) and, for the plan-view
figure, results/ctf_v1/geojson/<stem>.geojson. Writes
    numbers_e4.tex    \\newcommand macros for every E4 number quoted in the text
    tab_ctf.tex       lane metrics per module system and strategy (shared layout)
    fig_ctf_lanes.pdf base lanes of one 2:1 paddock for B1, B3, B3c and B3n
"""
import argparse
import json
import os

import numpy as np
import pandas as pd
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from shapely.geometry import shape, LineString, MultiLineString  # noqa: E402
from shapely.ops import unary_union  # noqa: E402

from figures import INK, INK2, MUTED, W2, MM, panel_label  # noqa: E402  (shared style)

RATIOS = ["1:1", "2:1", "3:1"]
RWORD = {"1:1": "One", "2:1": "Two", "3:1": "Three"}
TAB_STRAT = ["B1", "B2", "B3", "B3c", "B3n", "B3n_k2", "B4"]
SWORD = {"A": "A", "B1": "BOne", "B2": "BTwo", "B3": "BThree", "B3c": "BThreeC", "B3n": "BThreeN",
         "B3n_k2": "BThreeNK", "B3n_s12": "BThreeNS", "B4": "BFour", "B3c_ctr": "BThreeCCtr",
         "B3n_ctr": "BThreeNCtr"}
TEX = {"B3c": "B3c", "B3n": "B3n", "B3n_k2": "B3n$_{k=2}$", "B3n_s12": "B3n$_{s=12}$"}


def load(root):
    d = pd.read_csv(os.path.join(root, "runs.csv"))
    d["error"] = d["error"].fillna("").astype(str)
    d["feasible"] = d["feasible"].astype(str).str.lower().isin(["true", "1"]) & (d["error"] == "")
    d["all_valid"] = d.lane_valid_pct >= 99.999
    d["all_valid_seeder"] = d.lane_valid_seeder_pct >= 99.999
    d["no_cross"] = (d.n_lane_crossings == 0) & (d.n_lane_overlaps == 0)
    d["clear"] = d.n_clear_fail_lanes == 0
    d["lanes_ok"] = d.all_valid & d.no_cross & d.clear
    d["ctf_ok"] = d.feasible & d.lanes_ok
    return d


def main_set(d):
    """Shared lane layout, road gate, paddocks with obstacles (the E1 design + B4)."""
    return d[(d.lane_layout == "shared") & (d.gate_type == "road") & (d.density_per_ha > 0)]


def summary(s):
    g = s.groupby(["module_ratio", "strategy"])
    t = g.agg(n=("feasible", "size"), feas=("feasible", "mean"), valid=("all_valid", "mean"),
                 valid_seed=("all_valid_seeder", "mean"), nocross=("no_cross", "mean"),
                 cross=("n_lane_crossings", "median"), clear=("clear", "mean"), ok=("ctf_ok", "mean"),
                 lanes_ok=("lanes_ok", "mean"), brk=("n_lane_breaks", "median"),
                 offl=("off_lane_wheel_sprayer_m", "median"), sown=("sown_missed_sc_pct", "mean"),
                 traf=("unique_trafficked_ha", "mean"), time=("time_min", "mean"),
                 feas_n=("feasible", "sum"), ok_n=("ctf_ok", "sum"))
    # Sprayer feasibility and CTF validity over ALL paddocks of the design (as in E1): B1/B2 have no row
    # where no mainland was left, which counts as infeasible. B4 runs on the E3 subset (its own n).
    n_all = s[s.strategy == "A"].groupby("module_ratio").instance_id.nunique()
    for (r, st), x in t.iterrows():
        n = x.n if st == "B4" else n_all[r]
        t.loc[(r, st), "feas"] = x.feas_n / n
        t.loc[(r, st), "ok"] = x.ok_n / n
    return t


def tab_ctf(t, out):
    def p(v):
        return f"{100 * v:.0f}"
    lines = [r"% generated by analysis/analyse_e4.py; do not edit",
             r"\begin{tabular}{@{}llrrrrrrrr@{}}", r"\toprule",
             r"System & Strategy & \makecell{Sprayer\\feasible (\%)} & \makecell{Lanes\\drivable (\%)}"
             r" & \makecell{Lanes\\clear (\%)} & \makecell{No crossing\\or overlap (\%)}"
             r" & \makecell{CTF-valid\\layout (\%)} & \makecell{Lane\\breaks} & \makecell{Off-lane\\wheel (km)}"
             r" & \makecell{Unsown\\(\%)} \\", r"\midrule"]
    for i, r in enumerate(RATIOS):
        first = True
        for s in TAB_STRAT:
            if (r, s) not in t.index:
                continue
            x = t.loc[(r, s)]
            lab = f"{r} ({12 * RATIOS.index(r) + 12} m)" if first else ""
            first = False
            lines.append(f"{lab} & {TEX.get(s, s)} & {p(x.feas)} & {p(x.valid)} & {p(x.clear)} & {p(x.nocross)}"
                         f" & {p(x.ok)} & {x.brk:.0f} & {x.offl / 1000:.1f} & {x.sown:.1f} \\\\")
        if i < len(RATIOS) - 1:
            lines.append(r"\addlinespace")
    lines += [r"\botrule", r"\end{tabular}"]
    with open(os.path.join(out, "tab_ctf.tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


