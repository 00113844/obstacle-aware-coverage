"""Analysis of experiments E2 (native F2C vs extended workflow, R8) and B4 straddle (R9).

    python analyse_e2_b4.py RESULTS_ROOT [--out ../generated]

RESULTS_ROOT contains native_v1/runs.csv and b4_v1/runs.csv. Writes
    numbers_e2b4.tex   \\newcommand macros for every number quoted in the text
    tab_native.tex     native configurations (decomposition x route order) and extended strategies
    tab_b4.tex         B3 vs B4 by implement width and obstacle type
    fig_native.pdf     a: feasibility vs operational time per configuration; b: per-instance best plans
Population for E2: instances with obstacles (1 ha^-1), SC on. Error rows count as infeasible.
"""
import argparse
import os

import numpy as np
import pandas as pd
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from figures import COL, NAME, INK, INK2, MUTED, W2, MM, panel_label  # noqa: E402  (shared style)

DEC = {"none": "none", "boustrophedon": "Boustrophedon", "trapezoidal": "trapezoidal"}
ORD = {"boustrophedon": "boustrophedon", "snake": "snake", "spiral": "spiral",
       "rp_first": "OR-Tools, first", "rp_gls": "OR-Tools, GLS"}
DEC_MARK = {"none": "o", "boustrophedon": "s", "trapezoidal": "^"}
W = {12: "Twelve", 24: "TwentyFour", 36: "ThirtySix"}
S = {"A": "A", "B1": "BOne", "B2": "BTwo", "B3": "BThree", "B4": "BFour"}


def _feas(df):
    err = df["error"].fillna("").astype(str).replace("nan", "")
    ok = df["status"].eq("ok") if "status" in df else err.eq("")
    return df["feasible"].astype(str).str.lower().isin(["true", "1"]) & ok & err.eq("")


def load_native(root):
    n = pd.read_csv(os.path.join(root, "native_v1", "runs.csv"))
    n["feasible"] = _feas(n)
    n["t_plan"] = n[["t_hg_s", "t_decomp_s", "t_sg_s", "t_rp_s", "t_pp_s"]].sum(axis=1, min_count=1)
    n["passes"] = n["n_passes"].fillna(n["n_swaths"] + n["k_headland"])
    n["config"] = n["decomp"].fillna("") + "|" + n["sg_obj"].fillna("") + "|" + n["route_order"] + "|" + n["turn_model"]
    return n


def load_b4(root):
    b = pd.read_csv(os.path.join(root, "b4_v1", "runs.csv"))
    b["feasible"] = _feas(b.assign(status="ok"))
    return b


def summary(g):
    return pd.Series({
        "n": len(g), "feas": 100 * g.feasible.mean(), "time": g.time_min.median(), "eta": g.eta_pct.median(),
        "passes": g.passes.median(), "man": g.n_manoeuvres.median(), "oc": g.over_crop_m.median(),
        "miss": g.missed_pct.median(), "tplan": g.t_plan.median(),
        "time_feas": g.loc[g.feasible, "time_min"].median() if g.feasible.any() else np.nan,
    })


def tab_native(e2, out):
    nat = e2[e2.pipeline == "native"]
    ext = e2[e2.pipeline == "extended"]
    rows = []
    for d in ("none", "boustrophedon", "trapezoidal"):
        for o in ("boustrophedon", "snake", "spiral", "rp_first", "rp_gls"):
            rows.append(("native", d, o, summary(nat[(nat.decomp == d) & (nat.route_order == o)])))
    for s in ("A", "B1", "B2", "B3"):
        rows.append(("ext", "", s, summary(ext[ext.route_order == s])))

    def f(v, p=0):
        return "--" if pd.isna(v) else f"{v:.{p}f}"

    n_nat = int(rows[0][3]["n"])
    n_ext = int(rows[-1][3]["n"])
    L = [r"\begin{tabular}{@{}llrrrrrrrrr@{}}", r"\toprule",
         r"Decomp. & Order / strategy & \makecell{Feasible\\(\%)} & \makecell{Time\\(min)} & \makecell{Time,\\feasible} & \makecell{$\eta$\\(\%)} & Passes & \makecell{Manoeu-\\vres} & \makecell{Over\\crop (m)} & \makecell{Missed\\(\%)} & \makecell{Planning\\(s)} \\",
         r"\midrule", rf"\multicolumn{{11}}{{l}}{{\emph{{Native Fields2Cover (obstacles as holes; {n_nat} attempted plans per row)}}}} \\"]
    last = None
    for kind, d, o, s in rows:
        if kind == "ext" and last == "native":
            L += [r"\midrule", rf"\multicolumn{{11}}{{l}}{{\emph{{Extended workflow (gate, Dubins CC turns; {n_ext} plans per row)}}}} \\"]
        last = kind
        lab_d = DEC[d] if kind == "native" else ""
        lab_o = ORD[o] if kind == "native" else NAME[o]
        L.append(f"{lab_d} & {lab_o} & {f(s.feas, 1)} & {f(s.time)} & {f(s.time_feas)} & {f(s.eta)} & {f(s.passes)} & {f(s.man)} & "
                 f"{f(s.oc)} & {f(s.miss, 1)} & {f(s.tplan, 1)} \\\\")
    L += [r"\botrule", r"\end{tabular}"]
    with open(os.path.join(out, "tab_native.tex"), "w") as fh:
        fh.write("% generated by analysis/analyse_e2_b4.py; do not edit\n" + "\n".join(L) + "\n")
    return rows


def per_instance(e2):
    """Best feasible plan per instance: native (all 180 configs, or Dubins CC only) vs extended."""
    nat = e2[(e2.pipeline == "native") & e2.feasible]
    ext = e2[(e2.pipeline == "extended") & e2.feasible & e2.route_order.isin(["B1", "B2", "B3"])]
    inst = e2[["instance_id", "width_m"]].drop_duplicates().set_index("instance_id")
    best_nat = nat.sort_values("time_min").groupby("instance_id").first()
    b3_rows = e2[(e2.pipeline == "extended") & (e2.route_order == "B3") & e2.feasible].groupby("instance_id").first()
    inst = inst.assign(nat_missed=best_nat.missed_pct, b3_missed=b3_rows.missed_pct)
    out = inst.assign(
        nat_best=nat.groupby("instance_id").time_min.min(),
        nat_cc=nat[nat.turn_model == "DubinsCC"].groupby("instance_id").time_min.min(),
        ext_best=ext.groupby("instance_id").time_min.min(),
        b3=e2[(e2.pipeline == "extended") & (e2.route_order == "B3") & e2.feasible].groupby("instance_id").time_min.min(),
    )
    return out


def fig_native(rows, pi, out):
    fig, (a, b) = plt.subplots(1, 2, figsize=(W2, 70 * MM), gridspec_kw=dict(width_ratios=[1.25, 1], wspace=0.32))
    for kind, d, o, s in rows:
        if kind == "native":
            a.plot(s.time, s.feas, DEC_MARK[d], ms=5, mfc="white", mec=INK2, mew=1.0, zorder=3)
        else:
            a.plot(s.time, s.feas, "o", ms=7, color=COL[o], mec="white", mew=0.8, zorder=4)
            off = (-12, 3) if o == "A" else (5, 3)
            a.annotate(o, (s.time, s.feas), xytext=off, textcoords="offset points", fontsize=7, color=INK)
    lab = {("none", "rp_first"): "RP first", ("none", "rp_gls"): "RP GLS", ("none", "boustrophedon"): "boustr.",
           ("none", "spiral"): "spiral", ("none", "snake"): "snake"}
    for kind, d, o, s in rows:
        if kind == "native" and (d, o) in lab:
            a.annotate(lab[(d, o)], (s.time, s.feas), xytext=(5, -9), textcoords="offset points", fontsize=6.5, color=INK2)
    a.set_xlabel("Median operational time (min)")
    a.set_ylabel("Feasible plans (%)")
    a.set_ylim(-5, 105)
    from matplotlib.lines import Line2D
    h = [Line2D([], [], ls="", marker=DEC_MARK[d], ms=5, mfc="white", mec=INK2) for d in DEC]
    a.legend(h, [f"native, decomp.: {DEC[d]}" for d in DEC], loc="upper right", fontsize=6.5, handletextpad=0.3)
    panel_label(a, "a")

    lo, hi = 50, 215
    nofeas_x = 205
    for w, mk in ((12, "o"), (24, "s")):
        q = pi[pi.width_m == w]
        q_ok = q.dropna(subset=["nat_best", "b3"])
        b.plot(q_ok.nat_best, q_ok.b3, mk, ms=5, color=COL["B3"], mec="white", mew=0.7, label=f"{w} m", zorder=3)
        miss = q[q.nat_best.isna() & q.b3.notna()]
        if len(miss):
            b.plot(np.full(len(miss), nofeas_x), miss.b3, mk, ms=5, mfc="white", mec=COL["B3"], mew=1.0, zorder=3)
            b.annotate("no feasible\nnative plan", (nofeas_x, miss.b3.iloc[0]), xytext=(-4, -30),
                       textcoords="offset points", ha="center", fontsize=6.5, color=INK2,
                       arrowprops=dict(arrowstyle="-", color=MUTED, lw=0.6))
    b.plot([lo, hi], [lo, hi], color=MUTED, lw=0.8, ls="--", zorder=1)
    b.text(112, 120, "1:1", rotation=45, ha="center", fontsize=7, color=MUTED)
    b.text(hi - 4, lo + 4, "below the line: B3 faster", fontsize=6.5, color=MUTED, ha="right")
    b.set_xlim(lo, hi); b.set_ylim(lo, hi)
    b.set_xlabel("Best feasible native plan (min)")
    b.set_ylabel("B3 drive-around (min)")
    b.legend(title="Implement width", fontsize=6.5, title_fontsize=6.5, loc="upper left")
    panel_label(b, "b")
    fig.savefig(os.path.join(out, "fig_native.pdf"))
    plt.close(fig)


def tab_b4(b, out):
    s = b[b.sc == 1]
    L = [r"\begin{tabular*}{\columnwidth}{@{\extracolsep\fill}llrrrrr}", r"\toprule",
         r"$w$ & Strategy & \makecell{Feasible,\\outcrops (\%)} & \makecell{Feasible,\\mixed (\%)} & \makecell{Unplaced\\detours} & \makecell{Missed\\(\%)} & \makecell{Time vs\\A (\%)} \\",
         r"\midrule"]
    a = s[s.strategy == "A"].set_index("instance_id").time_min
    for w in (12, 24, 36):
        for st in ("B3", "B4"):
            g = s[(s.width_m == w) & (s.strategy == st)]
            fo = 100 * g[g.obstacle_type == "outcrop"].feasible.mean()
            fm = 100 * g[g.obstacle_type == "mixed"].feasible.mean()
            dt = (100 * (g.set_index("instance_id").time_min - a) / a).dropna().mean()
            L.append(f"{'' if st == 'B4' else str(w) + ' m'} & {st} & {fo:.1f} & {fm:.1f} & {g.n_unplaced_detours.mean():.2f} & "
                     f"{g.missed_pct.mean():.2f} & {dt:.1f} \\\\")
        if w != 36:
            L.append(r"\addlinespace")
    L += [r"\botrule", r"\end{tabular*}"]
    with open(os.path.join(out, "tab_b4.tex"), "w") as fh:
        fh.write("% generated by analysis/analyse_e2_b4.py; do not edit\n" + "\n".join(L) + "\n")


def numbers(n, e2, rows, pi, b, out):
    nat_all = n[n.pipeline == "native"]
    nat = e2[e2.pipeline == "native"]
    ext = e2[e2.pipeline == "extended"]
    nums = {
        "ENInstances": n.instance_id.nunique(),
        "ENInstancesObst": e2.instance_id.nunique(),
        "ENNativeRows": len(nat_all),
        "ENConfigs": nat_all.config.nunique(),
        "ENErrors": int((nat_all.status != "ok").sum()),
        "ENTimeouts": int((nat_all.status == "timeout").sum()),
        "ENFeasNativePct": 100 * nat.feasible.mean(),
        "ENNegClearPct": 100 * (nat.min_clearance_m < 0).mean(),
        "ENTurnFailPct": 100 * ((nat.min_clearance_turn_m < 0) & ~(nat.min_clearance_work_m < 0)).sum()
        / max(1, (nat.min_clearance_m < 0).sum()),
        "ENPlansN": len(nat),
        "ENNegClearN": int((nat.min_clearance_m < 0).sum()),
        "ENNegTurnN": int((nat.min_clearance_turn_m < 0).sum()),
        "ENNegWorkN": int((nat.min_clearance_work_m < 0).sum()),
        "ENWorkClearMissingN": int(nat[nat.status == "ok"].min_clearance_work_m.isna().sum()),
        "ENErrorPlansN": int((nat.status != "ok").sum()),
    }
    for t, k in (("Dubins", "Dubins"), ("DubinsCC", "DubinsCC"), ("ReedsShepp", "RS"), ("ReedsSheppHC", "RSHC")):
        nums[f"ENFeas{k}Pct"] = 100 * nat[nat.turn_model == t].feasible.mean()
    for so, k in (("NSwath", "NSwath"), ("NSwathModified", "NSwathMod"), ("SwathLength", "SwathLength")):
        nums[f"ENFeas{k}Pct"] = 100 * nat[nat.sg_obj == so].feasible.mean()
    R = {(d, o): s for kind, d, o, s in rows if kind == "native"}
    X = {o: s for kind, d, o, s in rows if kind == "ext"}
    dn = {"none": "None", "boustrophedon": "Bou", "trapezoidal": "Trap"}
    on = {"boustrophedon": "Bou", "snake": "Snake", "spiral": "Spiral", "rp_first": "RPFirst", "rp_gls": "RPGLS"}
    for (d, o), s in R.items():
        for col, k, p in (("feas", "Feas", 1), ("time", "Time", 0), ("oc", "OverCrop", 0), ("miss", "Missed", 1),
                          ("tplan", "Plan", 1), ("man", "Man", 0), ("eta", "Eta", 0)):
            nums[f"EN{dn[d]}{on[o]}{k}"] = (s[col], p)
    for o, s in X.items():
        for col, k, p in (("feas", "Feas", 0), ("time", "Time", 0), ("oc", "OverCrop", 0), ("miss", "Missed", 1),
                          ("man", "Man", 0), ("eta", "Eta", 0), ("tplan", "Plan", 1)):
            nums[f"EX{S[o]}{k}"] = (s[col], p)
    # decomposition: medians over all orders
    for d in ("none", "boustrophedon", "trapezoidal"):
        g = nat[nat.decomp == d]
        nums[f"EN{dn[d]}TimeAll"] = (g.time_min.median(), 0)
        nums[f"EN{dn[d]}MissedAll"] = (g.missed_pct.median(), 1)
    sorters = nat[nat.route_order.isin(["boustrophedon", "snake", "spiral"])]
    nums["ENSorterFeasPct"] = 100 * sorters.feasible.mean()
    # per-instance best plans
    nums["EPINInst"] = (len(pi), 0)
    nums["EPINatAny"] = (int(pi.nat_best.notna().sum()), 0)
    nums["EPIExtAny"] = (int(pi.ext_best.notna().sum()), 0)
    nums["EPIBThreeAny"] = (int(pi.b3.notna().sum()), 0)
    both = pi.dropna(subset=["nat_best", "b3"])
    r = both.b3 / both.nat_best
    nums["EPIRatioMed"] = (r.median(), 2)
    nums["EPIBThreeFasterN"] = (int((r < 1).sum()), 0)
    nums["EPIBThreeSlowerN"] = (int((r > 1).sum()), 0)
    nums["EPIBothN"] = (len(both), 0)
    dm = both.b3_missed - both.nat_missed
    nums["EPIdMissedMed"] = (dm.median(), 2)
    nums["EPIBThreeMissedLowerN"] = (int((dm < 0).sum()), 0)
    bcc = pi.dropna(subset=["nat_cc", "b3"])
    nums["EPICCBothN"] = (len(bcc), 0)
    nums["EPICCFasterN"] = (int((bcc.b3 < bcc.nat_cc).sum()), 0)
    for w in (12, 24):
        q = both[both.width_m == w]
        rr = 100 * (q.b3 / q.nat_best - 1)
        nums[f"EPIDiffW{W[w]}Med"] = (rr.median(), 1)
        nums[f"EPIDiffW{W[w]}Min"] = (rr.min(), 1)
        nums[f"EPIDiffW{W[w]}Max"] = (rr.max(), 1)
    bc = pi.dropna(subset=["nat_cc", "b3"])
    nums["EPINatCCAny"] = (int(pi.nat_cc.notna().sum()), 0)
    nums["EPIRatioCCMed"] = ((bc.b3 / bc.nat_cc).median(), 2)

    # ---- B4 ----
    s = b[b.sc == 1]
    nums["BFNInst"] = (s.instance_id.nunique(), 0)
    nums["BFNRows"] = (len(b), 0)
    for st in ("B3", "B4"):
        g = s[s.strategy == st]
        nums[f"BF{S[st]}FeasPct"] = 100 * g.feasible.mean()
        nums[f"BF{S[st]}Unplaced"] = (g.n_unplaced_detours.mean(), 2)
        for ot, k in (("outcrop", "Out"), ("mixed", "Mix")):
            nums[f"BF{S[st]}Feas{k}Pct"] = 100 * g[g.obstacle_type == ot].feasible.mean()
        for w in (12, 24, 36):
            gw = g[g.width_m == w]
            nums[f"BF{S[st]}FeasW{W[w]}Pct"] = 100 * gw.feasible.mean()
            nums[f"BF{S[st]}FeasOutW{W[w]}Pct"] = 100 * gw[gw.obstacle_type == "outcrop"].feasible.mean()
            nums[f"BF{S[st]}FeasMixW{W[w]}Pct"] = 100 * gw[gw.obstacle_type == "mixed"].feasible.mean()
        nums[f"BF{S[st]}Missed"] = (g.missed_pct.mean(), 2)
        nums[f"BF{S[st]}MinClearWork"] = (g.min_clearance_work_m.median(), 2)
        o = b[(b.sc == 0) & (b.strategy == st)]
        nums[f"BF{S[st]}OverlapOff"] = (o.overlap_pct.mean(), 1)
    p = s[s.strategy.isin(["B3", "B4"])].pivot_table(index="instance_id", columns="strategy",
                                                      values=["time_min", "missed_pct", "crit_C", "L_total_m", "feasible"],
                                                      aggfunc="first")
    d_L = p.L_total_m.B4 - p.L_total_m.B3
    nums["BFdLMed"] = (d_L.median(), 0)
    nums["BFdLPctMed"] = (100 * (d_L / p.L_total_m.B3).median(), 2)
    nums["BFShorterPct"] = 100 * (d_L < 0).mean()
    nums["BFdTimeMed"] = (( p.time_min.B4 - p.time_min.B3).median(), 2)
    nums["BFdMissedMed"] = ((p.missed_pct.B4 - p.missed_pct.B3).median(), 2)
    nums["BFMissedLowerPct"] = 100 * ((p.missed_pct.B4 - p.missed_pct.B3) < 0).mean()
    nums["BFdCPctMed"] = (100 * ((p.crit_C.B4 - p.crit_C.B3) / p.crit_C.B3).median(), 1)
    nums["BFCLowerPct"] = 100 * ((p.crit_C.B4 - p.crit_C.B3) < 0).mean()
    nums["BFGainedN"] = (int((p.feasible.B4.astype(int) - p.feasible.B3.astype(int) > 0).sum()), 0)
    nums["BFLostN"] = (int((p.feasible.B4.astype(int) - p.feasible.B3.astype(int) < 0).sum()), 0)

    with open(os.path.join(out, "numbers_e2b4.tex"), "w") as fh:
        fh.write("% generated by analysis/analyse_e2_b4.py; do not edit\n")
        for k, v in nums.items():
            if isinstance(v, tuple):
                v, prec = v
            else:
                prec = 1 if isinstance(v, float) else 0
            txt = "--" if pd.isna(v) else (f"{v:.{prec}f}" if isinstance(v, (float, np.floating)) else str(v))
            txt = r"\ensuremath{-}" + txt[1:] if txt.startswith("-") else txt
            fh.write(f"\\newcommand{{\\num{k}}}{{{txt}}}\n")
    return nums


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "generated"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    n = load_native(a.root)
    e2 = n[(n.density_per_ha > 0) & (n.sc == 1)]
    rows = tab_native(e2, a.out)
    pi = per_instance(e2)
    fig_native(rows, pi, a.out)
    b = load_b4(a.root)
    tab_b4(b, a.out)
    nums = numbers(n, e2, rows, pi, b, a.out)
    print(pi.round(1).to_string())
    for k, v in nums.items():
        print(k, v)


if __name__ == "__main__":
    main()
